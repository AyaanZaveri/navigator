const assert = require('node:assert/strict');
const { load } = require('./test-support/react-hooks.cjs');
const { createSearchResultsStore } = load('lib/search-results.ts', {}, { AbortController, Error });
const tick = () => new Promise(resolve => setImmediate(resolve));
const movie = { type: 'movie', id: '1', name: 'One' }, show = { type: 'series', id: '1', name: 'Show' };
const page = (results, totalPages = 3) => ({ results, totalPages, totalResults: 60 });
const initial = { page: 1, all: page([show, movie]), movie: page([movie]), series: page([show]) };
async function run() {
    const requests = [];
    const store = createSearchResultsStore(initial, (filter, number, signal) => new Promise((resolve, reject) => requests.push({ filter, number, signal, resolve, reject })));
    store.activate('all');
    const first = store.getSnapshot().all.results[0];
    const loading = store.loadMore('all'); store.loadMore('all');
    assert.equal(requests.length, 1, 'Intersecting repeatedly must issue one request');
    assert.equal(requests[0].number, 2);
    const second = { type: 'movie', id: '2', name: 'Two' };
    requests[0].resolve(page([movie, second, second])); await loading;
    assert.deepEqual(Array.from(store.getSnapshot().all.results, x => x.type + x.id), ['series1', 'movie1', 'movie2']);
    assert.equal(store.getSnapshot().all.results[0], first, 'Appending must not change the palette poster or existing card objects');
    const failed = store.loadMore('all'); requests.at(-1).reject(new Error('Try later')); await failed;
    assert.equal(store.getSnapshot().all.nextPage, 3, 'Failure must not skip a page');
    assert.equal(store.getSnapshot().all.results.length, 3, 'Errors retain already loaded titles');
    const before = requests.length; await store.loadMore('all'); assert.equal(requests.length, before, 'Errors require explicit retry');
    const retry = store.loadMore('all', true); assert.equal(requests.at(-1).number, 3);
    requests.at(-1).resolve(page([], 3)); await retry;
    await store.loadMore('all'); assert.equal(requests.length, before + 1, 'Final page stops loading');
    store.activate('movie');
    const stale = store.loadMore('movie'); const old = requests.at(-1);
    store.activate('series'); assert.equal(old.signal.aborted, true, 'Changing type cancels the old request');
    old.resolve(page([{ type: 'movie', id: 'stale' }])); await stale;
    assert.equal(store.getSnapshot().movie.results.length, 1, 'An aborted request cannot publish even if fetch ignores abort');
    const shows = store.loadMore('series'); requests.at(-1).resolve(page([show, { type: 'series', id: '2' }], 2)); await shows;
    store.activate('all'); assert.equal(store.getSnapshot().all.results.length, 3, 'Each filter retains its complete loaded feed');
    store.activate('movie');
    const movies = store.loadMore('movie'); requests.at(-1).resolve(page([{ ...second, name: 'New metadata' }], 2)); await movies;
    assert.equal(store.getSnapshot().movie.results.at(-1), second, 'A card keeps its object across rankings');
    const capped = createSearchResultsStore({ ...initial, all: page([movie], 1) }, () => { throw Error('Unexpected load'); });
    capped.activate('all'); await capped.loadMore('all');
    store.stop();
    const count = requests.length; await store.loadMore('all'); assert.equal(requests.length, count, 'Unmounted views cannot load');
    store.activate('series'); await store.loadMore('series'); assert.equal(requests.length, count, 'Strict Mode replay retains completed state');
    store.stop();
    let resolveOld, oldSignal;
    const removed = createSearchResultsStore(initial, (_filter, _page, signal) => { oldSignal = signal; return new Promise(resolve => resolveOld = resolve); });
    removed.activate('all'); const oldRequest = removed.loadMore('all'); removed.stop();
    assert.equal(oldSignal.aborted, true);
    resolveOld(page([second])); await oldRequest;
    assert.equal(removed.getSnapshot().all.results.length, 2, 'Unmount cannot publish late results');
    const loaded = [];
    const limit = createSearchResultsStore({ ...initial, all: page([movie], 999) }, async (_filter, number) => { loaded.push(number); return page([movie], 999); });
    limit.activate('all'); for (let i = 0; i < 505; i++) await limit.loadMore('all');
    assert.equal(loaded.length, 499); assert.equal(loaded.at(-1), 500, 'Never request past TMDB page 500'); limit.stop();
    console.log('PASS: infinite search ordering, deduplication, single flight, retry, filter caches, stale cancellation and final-page termination.');
}
run().catch(error => { console.error(error); process.exitCode = 1; });
