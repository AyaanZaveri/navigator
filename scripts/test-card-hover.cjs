const assert = require('node:assert/strict');
const fs = require('node:fs');
const postcss = require('postcss');
const css = postcss.parse(fs.readFileSync('components/media-card.module.css', 'utf8'));
const rules = [];
css.walkRules(rule => rules.push(rule));
const rule = selector => rules.find(item => item.selector === selector);
const declaration = (selector, property) => rule(selector)?.nodes.find(node => node.prop === property)?.value;
assert.equal(declaration('.playButton', 'opacity'), '0', 'The Play surface must start transparent so its blur can fade rather than pop into visibility');
assert.ok(declaration('.playButton', 'transition').includes('opacity'), 'The whole button surface needs an opacity transition');
assert.equal(declaration('.playButton', 'visibility'), undefined, 'Hover must not create/destroy the WebKit blur layer via visibility');
assert.equal(declaration('.card:hover .playButton', 'opacity'), '1');
assert.equal(declaration('.card:has(:focus-visible) .playButton', 'opacity'), '1');
const touch = rules.find(item => item.selector === '.playButton' && item.parent.type === 'atrule' && item.parent.params.includes('hover: none'));
assert.equal(touch.nodes.find(node => node.prop === 'opacity').value, '1', 'Touch keeps Play available without hovering');
assert.equal(declaration('.playButton', 'pointer-events'), 'none');
assert.equal(declaration('.card:hover .playButton', 'pointer-events'), 'auto');
assert.equal(declaration('.playOverlay', 'pointer-events'), 'none', 'The overlay must not interrupt the underlying card hover target');
console.log('PASS: continuous Play-surface fade, stable blur layer, hover/focus/touch reveal, and hit-testing');

const resume = '.card[data-continue-watching] .artwork';
assert.equal(declaration(resume, 'filter'), undefined, 'The zooming image must not also own a brightness filter in WebKit');
const shade = '.card[data-continue-watching] .frame::before';
assert.equal(declaration(shade, 'background'), 'rgb(0 0 0 / 35%)');
assert.equal(declaration(shade, 'pointer-events'), 'none');
assert.equal(declaration(shade, 'z-index'), '20', 'Base shade stays below the wordmark and hover scrim');
assert.equal(declaration(':global(html[data-native-platform="macos"]) .wordmark', 'transform'), 'translateZ(0)', 'Keep the filtered wordmark layer stable while artwork zoom starts and stops');
assert.equal(declaration(resume, 'transform'), undefined, 'Continue Watching keeps the shared hover zoom');
assert.equal(declaration('.card:hover .artwork', 'transform'), 'scale(1.02)');
assert.equal(declaration('.card:hover .playOverlay::before', 'opacity'), '1');
assert.notEqual(declaration('.card[data-continue-watching] .playOverlay::before', 'display'), 'none', 'Continue Watching retains hover dimming');
assert.equal(declaration('.artwork', 'filter'), undefined, 'Ordinary posters keep their existing brightness');
const macArtwork = ':global(html[data-native-platform="macos"]) .card[data-continue-watching] .artwork';
const macHover = ':global(html[data-native-platform="macos"]) .card[data-continue-watching]:hover .artwork';
assert.equal(declaration(macArtwork, 'transition'), undefined, 'macOS inherits the shared zoom transition');
assert.equal(declaration(macArtwork, 'transform'), 'translateZ(0) scale(1)', 'Keep the image composited before hover');
assert.equal(declaration(macHover, 'transform'), 'translateZ(0) scale(1.02)', 'Hover preserves the compositing transform while changing scale');
assert.equal(rule(macHover).parent.params, '(hover: hover) and (pointer: fine) and (prefers-reduced-motion: no-preference)', 'Touch and reduced motion do not trigger zoom');
console.log('PASS: fixed base shade, stable macOS wordmark and backdrop transform endpoints, gated hover zoom and Play dimming');
