const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { load } = require('./test-support/react-hooks.cjs');
const { MpvController } = load('lib/desktop/mpv-controller.ts', { '@/lib/media/playback-preferences': { readPlaybackPreferences: () => ({ audioLanguage: 'en' }) } }, { Event, EventTarget, CustomEvent, DOMException, URL, crypto, setTimeout, clearTimeout });
let receive;
const media = new MpvController({ platform: 'macos', send() {}, subscribe: fn => { receive = fn; return () => {}; } });
media.load('https://fixture.test/video.mkv');
const state = { position: 100, duration: 300, paused: false, volume: 1, muted: false, rate: 1, buffering: false, seeking: false, buffered: 200, width: 160, height: 90 };
receive({ type: 'state', session: media.previewSession, state: { ...state, bufferedRanges: [{ start: 150, end: 170 }, { start: 100, end: 120 }, { start: 110, end: 130 }] } });
assert.equal(media.buffered.length, 2);
assert.equal(media.buffered.start(0), 100, 'Resumed playback must not claim the entire preceding file is buffered');
assert.equal(media.buffered.end(0), 130); assert.equal(media.buffered.end(1), 170);
assert.throws(() => media.buffered.start(2), { name: 'IndexSizeError' });
receive({ type: 'state', session: media.previewSession, state: { ...state, bufferedRanges: [] } });
assert.equal(media.buffered.length, 0, 'An empty real cache must not fall back to the guessed cache end');
receive({ type: 'state', session: media.previewSession, state });
assert.equal(media.buffered.end(0), 200, 'Older runtimes retain their legacy buffered-end contract');
media.dispose();
console.log('PASS: real native cached ranges, ordering/merging, empty cache, resume gaps and older runtimes');
