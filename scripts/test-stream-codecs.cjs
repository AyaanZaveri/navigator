const assert = require("node:assert/strict");
const ts = require("typescript");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const source = fs.readFileSync(path.join(__dirname, "../lib/media/stream-codecs.ts"), "utf8");
const js = ts.transpile(source.replace('import { languageMatchScore } from "@/lib/media/audio-language";', "const languageMatchScore = (a, b) => a === b || a.startsWith(b + '-') || b.startsWith(a + '-');").replace(/import type .*?;\n/, ""), { module: ts.ModuleKind.CommonJS });
const mod = { exports: {} };
vm.runInNewContext(`(function(exports, require, module){${js}\n})(mod.exports, require, mod)`, { mod, require });
const { audioCodecString, audioTrackMime, metadataAudioSupport } = mod.exports;
const track = (codec, extra = {}) => ({ codec, codecString: null, internalCodecId: null, ...extra });
const meta = (audio, video = track("h264")) => ({ mimeType: "video/mp4", video, audio });
const yes = () => true, no = () => false;
assert.equal(audioCodecString(track("aac")), "mp4a.40.2");
assert.equal(audioTrackMime(track("aac")), 'audio/mp4; codecs="mp4a.40.2"');
assert.equal(metadataAudioSupport(meta([track("aac", { primary: true })]), yes), "supported");
assert.equal(metadataAudioSupport(meta([]), yes), "unsupported");
assert.equal(metadataAudioSupport(meta([track("mystery")]), yes), "unknown");
assert.equal(metadataAudioSupport(meta([track("aac", { primary: true }), track("dts")]), yes), "supported");
assert.equal(metadataAudioSupport(meta([track("aac", { primary: true }), track("dts")]), no), "unknown");
for (const [codec, expected] of [["eac3", "ec-3"], ["ac3", "ac-3"], ["DTS-HD", "dtsc"], ["TrueHD", "mlpa"], ["pcm_s16le", "pcm"]]) assert.equal(audioCodecString(track(codec)), expected);
assert.equal(metadataAudioSupport(meta([track("aac", { language: "eng" }), track("dts", { language: "fra" })]), yes, "fra"), "supported");
assert.equal(metadataAudioSupport(undefined, yes), "unknown");
console.log("stream codec tests passed");
